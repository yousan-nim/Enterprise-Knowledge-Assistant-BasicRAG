from pydantic import BaseModel, Field

from app.schemas.schemas import GroundedAnswer


class ChatRequest(BaseModel):
    question: str = Field(min_length=1, max_length=2000, description="Question text; whitespace-only input is rejected.", examples=["ค่าเดินทางเบิกได้สูงสุดเท่าไร?"])


class ChatResponse(BaseModel):
    answer: str = Field(description="Unverified response generated by the chat model.", examples=["Hello! How can I help?"])


class QuestionRequest(BaseModel):
    question: str = Field(min_length=1, max_length=2000, description="Question text; whitespace-only input is rejected.", examples=["ค่าเดินทางเบิกได้สูงสุดเท่าไร?"])
    top_k: int = Field(default=3, ge=1, le=10, description="Maximum retrieved chunks. May return fewer if the document has fewer chunks.", examples=[1])

class RetrievedSource(BaseModel):
    id: str = Field(description="Excerpt ID used by citation_ids.", examples=["chunk-2"])
    text: str = Field(description="Retrieved original text for evidence inspection.")
    source: str = Field(description="Uploaded document filename.", examples=["handbook.md"])
    score: float = Field(description="Cosine similarity; not a probability or factual confidence score.", examples=[0.4279])

class QuestionResponse(GroundedAnswer):
    sources: list[RetrievedSource] = Field(description="All retrieved excerpts, including when found is false.")
